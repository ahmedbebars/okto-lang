def enc(name):
    """Go names allow letters and digits only; anything else is spelled out."""
    out = []
    for ch in name:
        cat = unicodedata.category(ch)
        out.append(ch if ch == '_' or cat[0] == 'L' or cat == 'Nd' else '_x%04X_' % ord(ch))
    return ''.join(out)


def gt(t):
    """The Go type for an Okto type."""
    if t is None or t in ('none', 'error'):
        return 'any'
    if t in GO_BASIC:
        return GO_BASIC[t]
    if is_list(t):
        return '[]' + gt(t[1])
    if is_dict(t):
        return '*OMap[%s, %s]' % (gt(t[1]), gt(t[2]))
    if is_rec(t):
        return 'R_' + enc(t[1])
    return 'Opt[%s]' % gt(t[1])


def gstr(s):
    return json.dumps(s, ensure_ascii=False)


