    def __init__(self):
        self.lines, self.ind, self.n = [], 0, 0
        self.top = True
        self.web = False

    def w(self, s):
        self.lines.append('\t' * self.ind + s)

    @staticmethod
    def name(n):
        return 'u_' + enc(n)

    def program(self, ast):
        for s in ast:
            if s.k == 'record':
                self.record(s)
        for s in ast:
            if s.k == 'decl':
                self.w('var %s %s' % (self.name(s.name), gt(s.vt)))
        for s in ast:
            if s.k == 'fn':
                self.fn(s)
        self.w('func main() {')
        self.ind += 1
        self.w('defer okEnd()')
        for kind in ('read', 'write', 'env', 'serve'):
            values = [gstr(s.value) for s in ast if s.k == 'allow' and s.kind == kind]
            if values:
                self.w('okAllow[%s] = []string{%s}' % (gstr(kind), ', '.join(values)))
